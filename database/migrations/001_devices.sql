-- Migration 001 (2026-10-16): field devices (Raspberry Pi) that send events to the event service.
-- Run it by hand on the production database BEFORE deploying a backend that includes devices: the backend
-- validates its tables at start-up and refuses to start without this one. Safe to run more than once.
-- The same statements are in schema.sql, so a database created from scratch already has the table.
--
-- Each device belongs to one crop. Its key is shown once when it is registered (POST /api/devices) and only
-- its SHA-256 is stored here, as 64 hexadecimal characters.

CREATE TABLE IF NOT EXISTS devices (
    id_device     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_crop       INTEGER     NOT NULL,
    device_code   VARCHAR(64) NOT NULL,
    key_hash      VARCHAR(64) NOT NULL,
    active        BOOLEAN     NOT NULL DEFAULT TRUE,
    last_event_at TIMESTAMP,
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_devices_crop FOREIGN KEY (id_crop) REFERENCES crops (id_crop) ON DELETE CASCADE,
    CONSTRAINT uq_devices_code UNIQUE (device_code)
);

CREATE INDEX IF NOT EXISTS idx_devices_crop ON devices (id_crop);
