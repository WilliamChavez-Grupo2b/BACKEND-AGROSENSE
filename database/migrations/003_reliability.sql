ALTER TABLE irrigations ADD COLUMN IF NOT EXISTS moisture_before NUMERIC(5, 2);
ALTER TABLE irrigations ADD COLUMN IF NOT EXISTS moisture_after NUMERIC(5, 2);

CREATE TABLE IF NOT EXISTS irrigation_dispatches (
    id_dispatch  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_crop      INTEGER     NOT NULL,
    minutes      INTEGER     NOT NULL,
    source       VARCHAR(16) NOT NULL,
    confidence   NUMERIC(5, 4),
    status       VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    created_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at   TIMESTAMP   NOT NULL,
    delivered_at TIMESTAMP,
    confirmed_at TIMESTAMP,
    CONSTRAINT fk_dispatches_crop FOREIGN KEY (id_crop) REFERENCES crops (id_crop) ON DELETE CASCADE,
    CONSTRAINT ck_dispatches_status CHECK (status IN ('PENDING', 'DELIVERED', 'STARTED', 'REFUSED', 'EXPIRED')),
    CONSTRAINT ck_dispatches_source CHECK (source IN ('MANUAL', 'AI')),
    CONSTRAINT ck_dispatches_minutes CHECK (minutes > 0)
);

CREATE TABLE IF NOT EXISTS sensor_readings_hourly (
    id_hourly  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sensor  INTEGER        NOT NULL,
    hour_start TIMESTAMP      NOT NULL,
    avg_value  NUMERIC(12, 4) NOT NULL,
    min_value  NUMERIC(12, 4) NOT NULL,
    max_value  NUMERIC(12, 4) NOT NULL,
    samples    INTEGER        NOT NULL,
    CONSTRAINT fk_readings_hourly_sensor FOREIGN KEY (id_sensor) REFERENCES sensors (id_sensor) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_dispatches_crop_status ON irrigation_dispatches (id_crop, status);
CREATE INDEX IF NOT EXISTS idx_readings_hourly_sensor ON sensor_readings_hourly (id_sensor, hour_start);
